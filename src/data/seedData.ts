export function getMotorcycleFieldValue(
  moto: Motorcycle,
  fieldKey: string
): string {
  switch (fieldKey) {
    case 'brand':
      return moto.brand;
    case 'family':
      return moto.family;
    case 'model':
      return moto.model;
    case 'displacementCc':
      return `${moto.displacementCc} cc`;
    case 'engineType':
      return moto.engineType;
    case 'powerHp':
      return moto.powerHp;
    case 'transmission':
      return moto.transmission;
    case 'cooling':
      return moto.cooling;
    case 'brakes':
      return moto.brakes;
    case 'tankLiters':
      return moto.tankLiters;
    case 'topSpeedKmh':
      return `${moto.topSpeedKmh} km/h`;
    case 'breakInNotes':
      return moto.breakInNotes;
    case 'highlights':
      return moto.highlights.join(' · ');
    default:
      return moto.customSpecs?.[fieldKey]?.trim() || '';
  }
}

function fillTemplatePlaceholders(
  text: string,
  moto: Motorcycle,
  fieldValue: string
): string {
  return text
    .replace(/\{modelo\}/gi, moto.model)
    .replace(/\{marca\}/gi, moto.brand)
    .replace(/\{familia\}/gi, moto.family)
    .replace(/\{valor\}/gi, fieldValue)
    .replace(/\{displacementCc\}/gi, `${moto.displacementCc} cc`)
    .replace(/\{engineType\}/gi, moto.engineType)
    .replace(/\{powerHp\}/gi, moto.powerHp)
    .replace(/\{transmission\}/gi, moto.transmission)
    .replace(/\{cooling\}/gi, moto.cooling)
    .replace(/\{brakes\}/gi, moto.brakes)
    .replace(/\{tankLiters\}/gi, moto.tankLiters)
    .replace(/\{topSpeedKmh\}/gi, `${moto.topSpeedKmh} km/h`);
}

export function generateDynamicQuestions(
  motorcycles: Motorcycle[],
  timeGuides: TimeGuideEntry[],
  adminQuizItems: Omit<AdminQuizItem, 'createdAt' | 'updatedAt'>[] = INITIAL_ADMIN_QUIZ_ITEMS
): QuizQuestion[] {
  const activeMotos = motorcycles.filter((m) => m.isActive);
  const activeGuides = timeGuides.filter((g) => g.isActive);
  const activeItems = adminQuizItems.filter((q) => q.isActive);
  const generated: QuizQuestion[] = [];

  for (const item of activeItems) {
    if (item.kind === 'fixed') {
      if (item.options.length >= 2) {
        generated.push({
          id: item.id,
          topic: item.topic,
          brand: item.brand,
          sourceSection: item.sourceSection,
          question: item.question,
          options: item.options,
          correctIndex: Math.min(item.correctIndex, item.options.length - 1),
          explanation: item.explanation,
        });
      }
      continue;
    }

    // Template question across matching models
    const matchingMotos = activeMotos.filter((m) => {
      if (item.brand !== 'AMBAS' && m.brand !== item.brand) return false;
      if (item.targetScope === 'FAMILY' && item.targetFamily) {
        return m.family === item.targetFamily;
      }
      if (item.targetScope === 'MODELS' && item.targetModelIds.length > 0) {
        return item.targetModelIds.includes(m.id);
      }
      return true;
    });

    // Pool of all distinct values across active catalog for this field
    const catalogValues = Array.from(
      new Set(
        activeMotos
          .map((m) => getMotorcycleFieldValue(m, item.sourceField))
          .filter(Boolean)
      )
    );

    matchingMotos.forEach((moto, idx) => {
      const correctVal = getMotorcycleFieldValue(moto, item.sourceField);
      if (!correctVal) return;

      const distractorPool = Array.from(
        new Set([
          ...catalogValues.filter((v) => v !== correctVal),
          ...item.options.filter((v) => v && v !== correctVal),
        ])
      );

      const wrongChoices = distractorPool
        .sort((a, b) =>
          (a.length + idx) % 2 === 0 ? a.localeCompare(b) : b.localeCompare(a)
        )
        .slice(0, 3);

      if (wrongChoices.length < 1) return;

      const opts = [correctVal, ...wrongChoices].sort((a, b) => {
        if (item.sourceField === 'displacementCc' || item.sourceField === 'topSpeedKmh') {
          return parseInt(a, 10) - parseInt(b, 10);
        }
        return (a.length + idx) % 2 === 0 ? a.localeCompare(b) : b.localeCompare(a);
      });

      generated.push({
        id: `${item.id}-${moto.id}`,
        topic: item.topic,
        brand: moto.brand,
        sourceSection: item.sourceSection,
        question: fillTemplatePlaceholders(item.question, moto, correctVal),
        options: opts,
        correctIndex: opts.indexOf(correctVal),
        explanation: fillTemplatePlaceholders(
          item.explanation || `En ${moto.model}, el apartado ${item.sourceSection} indica: ${correctVal}.`,
          moto,
          correctVal
        ),
      });
    });
  }

  // Dynamic Time Guide questions from live VC/VM entries
  activeGuides
    .filter((g) => ['VM01', 'VM10', 'VM13', 'VM14', 'VC05', 'VC11'].includes(g.code))
    .forEach((guide) => {
      const distractors = ['30 días', '3 meses', '3 años', '1 mes', 'Sin garantía']
        .filter((d) => d.toLowerCase() !== guide.motocicletasTime.toLowerCase())
        .slice(0, 3);
      const opts = [guide.motocicletasTime, ...distractors].sort((a, b) =>
        a.localeCompare(b)
      );
      generated.push({
        id: `dyn-tg-${guide.code}`,
        topic: 'Guía de Tiempos',
        brand: 'VENTO',
        sourceSection: `Guía de Tiempos · ${guide.code}`,
        question: `En la Guía de Tiempos 2025, ¿cuál es el tiempo de garantía para "${guide.code}: ${guide.component}" en Motocicletas?`,
        options: opts,
        correctIndex: opts.indexOf(guide.motocicletasTime),
        explanation: `${guide.code} (${guide.component}): Motocicletas = ${guide.motocicletasTime}. ${guide.notes}`,
      });
    });

  return generated;
}
