function inferSourceSectionForCurated(q: QuizQuestion): {
  sourceSection: string;
  sourceField: string;
} {
  if (q.topic === 'Garantías') {
    return {
      sourceSection:
        q.brand === 'AMERICAN PISTON'
          ? 'Póliza American Pistón'
          : 'Póliza VENTO 2025',
      sourceField: 'manual',
    };
  }
  if (q.topic === 'Guía de Tiempos') {
    return {
      sourceSection: 'Guía de Tiempos VC / VM 2025',
      sourceField: 'manual',
    };
  }
  if (q.topic === 'Familias') {
    return {
      sourceSection: 'Familias y Asentamiento VENTO',
      sourceField: 'family',
    };
  }
  return {
    sourceSection: 'Ficha Técnica · Motor y Transmisión',
    sourceField: 'manual',
  };
}

